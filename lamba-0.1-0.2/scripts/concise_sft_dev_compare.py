#!/usr/bin/env python3
"""Beat-ThinkingCap track: compare the new concise-SFT model's dev rollouts against the EXISTING
letterfix2-c10 baseline (already recorded in dev_candidates.jsonl -- these prompts' self_text IS
that baseline, since the mining pool's self-rollouts were generated by letterfix2-c10 itself).
Applies DS's exact pre-registered dev pass criteria (consult #110 retry)."""
import json, math, re, statistics as st
from pathlib import Path
from collections import Counter

AL = re.compile(r"[A-Za-z0-9]")
def loop_flags(text, prompt=""):
    n = len(text); cov = bytearray(n); seen = set(); found = False
    for i in range(0, max(0, n - 60), 30):
        w = text[i:i + 60]
        if w in seen or len(AL.findall(w)) < 25: continue
        seen.add(w)
        if text.count(w) < 4 or w in prompt: continue
        found = True; j = text.find(w)
        while j >= 0:
            for k in range(j, min(n, j + 60)): cov[k] = 1
            j = text.find(w, j + 60)
    tail = sum(cov[max(0, n - 2500):])
    return {"L": found, "R_any": tail > 0, "R_heavy": tail > 1500}

def mc(x, y):
    n = x + y
    return 1.0 if n == 0 else min(1.0, 2 * sum(math.comb(n, j) for j in range(min(x, y) + 1)) / 2 ** n)

def main():
    base = {c["id"]: c for c in (json.loads(l) for l in open("/home/ubuntu/antidoom_data/concise_sft/dev_candidates.jsonl"))}
    new = {json.loads(l)["id"]: json.loads(l) for l in open("/home/ubuntu/eval_results/loop_concisesft_g150.jsonl")}
    ids = sorted(set(base) & set(new))
    print(f"paired dev prompts: {len(ids)}")

    for i in ids:
        new[i]["flags"] = loop_flags(new[i]["text"], base[i]["prompt"])
        new[i]["n_tokens_real"] = new[i]["n_tokens"]

    base_tokens = [base[i]["n_tokens"] for i in ids]
    new_tokens = [new[i]["n_tokens_real"] for i in ids]
    print(f"\nMEAN TOKENS: base {st.mean(base_tokens):.1f} -> new {st.mean(new_tokens):.1f} "
          f"(ratio {st.mean(new_tokens)/st.mean(base_tokens):.4f}, target <=0.93)")

    def rate(d): return sum(d) / len(d)
    def row(name, base_flag_fn, new_flag_fn):
        b = [base_flag_fn(i) for i in ids]; n = [new_flag_fn(i) for i in ids]
        rb, rn = rate(b), rate(n)
        x = sum(bb and not nn for bb, nn in zip(b, n))
        y = sum(nn and not bb for bb, nn in zip(b, n))
        p = mc(x, y)
        diff_pp = 100 * (rn - rb)
        print(f"{name:10s} base {100*rb:5.1f}%  new {100*rn:5.1f}%  diff {diff_pp:+5.1f}pp  "
              f"(base-only {x} new-only {y}, McNemar p={p:.3g})  {'PASS' if diff_pp <= 2.0 else 'FAIL'} (<=2pp)")
        return diff_pp

    d_L = row("L", lambda i: base[i]["L"], lambda i: new[i]["flags"]["L"])
    d_Rany = row("R_any", lambda i: base[i]["R_any"], lambda i: new[i]["flags"]["R_any"])
    d_Rheavy = row("R_heavy", lambda i: base[i]["R_heavy"], lambda i: new[i]["flags"]["R_heavy"])
    d_budget = row("budget", lambda i: base[i]["budget_hit"], lambda i: new[i]["finish_reason"] == "length")

    ratio = st.mean(new_tokens) / st.mean(base_tokens)
    print(f"\n=== DEV PASS CHECK (DS consult #110 retry criteria) ===")
    checks = {
        "mean_tokens<=0.93x": ratio <= 0.93,
        "L_diff<=2pp": d_L <= 2.0,
        "R_any_diff<=2pp": d_Rany <= 2.0,
        "R_heavy_diff<=2pp": d_Rheavy <= 2.0,
        "budget_diff<=2pp": d_budget <= 2.0,
    }
    for k, v in checks.items():
        print(f"  {k}: {'PASS' if v else 'FAIL'}")
    overall = all(checks.values())
    print(f"\nOVERALL DEV: {'PASS -> proceed to 150-test' if overall else 'FAIL -> do not run 150-test yet'}")

    # domain breakdown
    print("\n--- by domain ---")
    doms = sorted(set(base[i]["domain"] for i in ids))
    for dom in doms:
        dids = [i for i in ids if base[i]["domain"] == dom]
        bt = [base[i]["n_tokens"] for i in dids]; nt = [new[i]["n_tokens_real"] for i in dids]
        print(f"{dom}: n={len(dids)} mean_tok base={st.mean(bt):.0f} new={st.mean(nt):.0f}")

if __name__ == "__main__":
    main()
